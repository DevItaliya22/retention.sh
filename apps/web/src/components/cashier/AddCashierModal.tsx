"use client";

import { zodResolver } from "@hookform/resolvers/zod";
import {
  Button,
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
  Input,
} from "@reelo/ui/components";
import { useDebouncedCallback } from "@reelo/ui/hooks";
import { RotateCw } from "lucide-react";
import { useEffect, useMemo, useRef } from "react";
import { useForm } from "react-hook-form";
import { toast } from "sonner";
import { z } from "zod";

import { useManageCashier } from "@/hooks/cashier/useManageCashier";
import { DialogSection } from "@reelo/ui/components";
import { createCashierSchema } from "@/lib/schemas/cashier";
import { generateSlug } from "@/lib/utils/slug";
import { getErrorMessageFromResponse } from "@/lib/utils/error-handler";

const addCashierSchema = createCashierSchema;

type AddCashierFormValues = z.infer<typeof addCashierSchema>;

interface AddCashierModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export function AddCashierModal({ isOpen, onClose }: AddCashierModalProps) {
  const { create, list } = useManageCashier();
  const slugTouchedRef = useRef(false);
  const lastAutoGeneratedSlugRef = useRef("");
  const slugFieldRef = useRef<{ onChange: (value: string) => void } | null>(
    null,
  );

  const form = useForm<AddCashierFormValues>({
    resolver: zodResolver(addCashierSchema),
    defaultValues: {
      name: "",
      email: "",
      password: "",
      cashierLinkSlug: "",
    },
  });

  const cashierName = form.watch("name");
  const cashierSlug = form.watch("cashierLinkSlug");

  const debouncedSetSlug = useDebouncedCallback((name: string) => {
    if (!slugTouchedRef.current && name) {
      const slug = generateSlug(name);
      lastAutoGeneratedSlugRef.current = slug;
      form.setValue("cashierLinkSlug", slug, { shouldValidate: true });
    }
  }, 500);

  useEffect(() => {
    if (cashierSlug && cashierSlug !== lastAutoGeneratedSlugRef.current) {
      slugTouchedRef.current = true;
    }
  }, [cashierSlug]);

  const slugAvailability = useMemo(() => {
    if (!cashierSlug || cashierSlug.trim().length === 0) {
      return { available: null, checking: false };
    }
    const normalized = generateSlug(cashierSlug.trim());
    if (normalized !== cashierSlug) {
      return { available: null, checking: false };
    }
    const isTaken = list.cashiers.some(
      (cashier) => cashier.cashierLinkSlug === normalized,
    );
    return { available: !isTaken, checking: false };
  }, [cashierSlug, list.cashiers]);

  const handleRegenerateSlug = () => {
    if (cashierName && slugFieldRef.current) {
      const slug = generateSlug(cashierName);
      slugFieldRef.current.onChange(slug);
      slugTouchedRef.current = false;
      lastAutoGeneratedSlugRef.current = slug;
    }
  };

  const handleSubmit = (data: AddCashierFormValues) => {
    if (!slugAvailability.available) {
      toast.error("This slug is already taken. Please choose another one.");
      form.setError("cashierLinkSlug", {
        message: "This slug is already taken. Please choose another one.",
      });
      return;
    }
    onClose();
    toast.promise(
      create.mutateAsync(data).then(() => {
        form.reset();
        slugTouchedRef.current = false;
        lastAutoGeneratedSlugRef.current = "";
      }),
      {
        loading: "Creating cashier...",
        success: "Cashier created successfully",
        error: (err: Error) =>
          getErrorMessageFromResponse(err, "Failed to create cashier. Please try again."),
      },
    );
  };

  const handleClose = () => {
    form.reset();
    slugTouchedRef.current = false;
    lastAutoGeneratedSlugRef.current = "";
    onClose();
  };

  return (
    <Dialog open={isOpen} onOpenChange={handleClose}>
      <DialogContent size="medium">
        <DialogHeader>
          <DialogTitle>Add Cashier</DialogTitle>
          <DialogDescription>
            Create a new cashier account for your business.
          </DialogDescription>
        </DialogHeader>
        <Form {...(form as any)}>
          <form onSubmit={form.handleSubmit(handleSubmit)}>
            <DialogSection padding="medium" className="space-y-4">
              <FormField
                control={form.control as any}
                name="name"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>Name</FormLabel>
                    <FormControl>
                      <Input
                        placeholder="Enter cashier name"
                        disabled={create.isPending}
                        className="placeholder:text-muted-foreground/60"
                        {...field}
                        onChange={(e) => {
                          field.onChange(e);
                          const value = e.target.value;
                          if (value && !slugTouchedRef.current) {
                            debouncedSetSlug(value);
                          }
                        }}
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <FormField
                control={form.control as any}
                name="email"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>Email</FormLabel>
                    <FormControl>
                      <Input
                        type="email"
                        placeholder="Enter email address"
                        disabled={create.isPending}
                        className="placeholder:text-muted-foreground/60"
                        {...field}
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <FormField
                control={form.control as any}
                name="password"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>Password</FormLabel>
                    <FormControl>
                      <Input
                        type="password"
                        placeholder="Enter password"
                        disabled={create.isPending}
                        className="placeholder:text-muted-foreground/60"
                        {...field}
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <FormField
                control={form.control as any}
                name="cashierLinkSlug"
                render={({ field }) => {
                  slugFieldRef.current = field;
                  return (
                    <FormItem>
                      <div className="flex items-center justify-between">
                        <FormLabel>Link Slug</FormLabel>
                        <Button
                          type="button"
                          variant="ghost"
                          size="sm"
                          className="h-6 px-2 text-xs"
                          onClick={handleRegenerateSlug}
                          disabled={!cashierName || create.isPending}
                        >
                          <RotateCw className="mr-1 h-3 w-3" />
                          Regenerate
                        </Button>
                      </div>
                      <FormControl>
                        <div className="focus-within:ring-ring flex items-center overflow-hidden rounded-md border shadow-sm focus-within:ring-1">
                          <Input
                            className="border-0 shadow-none focus-visible:ring-0 placeholder:text-muted-foreground/60"
                            placeholder="cashier-link-slug"
                            disabled={create.isPending}
                            {...field}
                          />
                          {(field.value ?? "").trim().length > 0 && (
                            <span
                              className={
                                slugAvailability.checking
                                  ? "text-muted-foreground px-3 text-xs"
                                  : slugAvailability.available === null
                                    ? "text-muted-foreground px-3 text-xs"
                                    : slugAvailability.available
                                      ? "px-3 text-xs text-green-600"
                                      : "px-3 text-xs text-red-600"
                              }
                            >
                              {slugAvailability.checking
                                ? "Checking…"
                                : slugAvailability.available === null
                                  ? ""
                                  : slugAvailability.available
                                    ? "Available"
                                    : "Not available"}
                            </span>
                          )}
                        </div>
                      </FormControl>
                      <FormMessage />
                    </FormItem>
                  );
                }}
              />
            </DialogSection>
            <DialogFooter>
              <Button
                type="button"
                variant="outline"
                onClick={handleClose}
                disabled={create.isPending}
              >
                Cancel
              </Button>
              <Button type="submit" loading={create.isPending}>
                Create Cashier
              </Button>
            </DialogFooter>
          </form>
        </Form>
      </DialogContent>
    </Dialog>
  );
}
