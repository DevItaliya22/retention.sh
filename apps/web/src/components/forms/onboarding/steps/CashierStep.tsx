"use client";

import type { WelcomeFormValues } from "@/lib/schemas/onboarding";
import { generateSlug } from "@/lib/utils/slug";
import {
  Button,
  Checkbox,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
  Input,
  useFormContext,
} from "@reelo/ui/components";
import { useDebouncedCallback } from "@reelo/ui/hooks";
import { RotateCw } from "lucide-react";
import { useEffect, useRef } from "react";

export function CashierStep() {
  const form = useFormContext<WelcomeFormValues>();
  const createCashier = form.watch("createCashier");
  const cashierName = form.watch("cashierName");
  const cashierSlug = form.watch("cashierLinkSlug");
  const slugTouchedRef = useRef(false);
  const lastAutoGeneratedSlugRef = useRef("");
  const slugFieldRef = useRef<{ onChange: (value: string) => void } | null>(
    null,
  );

  const debouncedSetSlug = useDebouncedCallback((name: string) => {
    if (!slugTouchedRef.current && name) {
      const slug = generateSlug(name);
      lastAutoGeneratedSlugRef.current = slug;
      form.setValue("cashierLinkSlug", slug, { shouldValidate: true });
    }
  }, 500);

  useEffect(() => {
    if (cashierSlug && cashierSlug !== lastAutoGeneratedSlugRef.current) {
      slugTouchedRef.current = true;
    }
  }, [cashierSlug]);

  const handleRegenerateSlug = () => {
    if (cashierName) {
      const slug = generateSlug(cashierName);
      form.setValue("cashierLinkSlug", slug, { shouldValidate: true });
      slugTouchedRef.current = false;
      lastAutoGeneratedSlugRef.current = slug;
    }
  };

  return (
    <div className="grid gap-6">
      <FormField
        control={form.control}
        name="createCashier"
        render={({ field }) => (
          <FormItem className="bg-muted/20 flex flex-row items-start space-y-0 space-x-3 rounded-md border p-4 shadow-sm">
            <FormControl>
              <Checkbox
                checked={field.value}
                onCheckedChange={field.onChange}
              />
            </FormControl>
            <div className="space-y-1 leading-none">
              <FormLabel className="cursor-pointer">
                Create a cashier account now?
              </FormLabel>
              <p className="text-muted-foreground text-sm">
                You can always add cashiers later from your dashboard.
              </p>
            </div>
          </FormItem>
        )}
      />

      {createCashier && (
        <div className="space-y-4">
          <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
            <FormField
              control={form.control}
              name="cashierName"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Name</FormLabel>
                  <FormControl>
                    <Input
                      placeholder="John Doe"
                      {...field}
                      value={field.value ?? ""}
                      onChange={(e) => {
                        field.onChange(e);
                        const value = e.target.value;
                        if (value && !slugTouchedRef.current) {
                          debouncedSetSlug(value);
                        }
                      }}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />
            <FormField
              control={form.control}
              name="cashierEmail"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Email</FormLabel>
                  <FormControl>
                    <Input
                      type="email"
                      placeholder="john@example.com"
                      {...field}
                      value={field.value ?? ""}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />
          </div>

          <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
            <FormField
              control={form.control}
              name="cashierLinkSlug"
              render={({ field }) => {
                slugFieldRef.current = field;
                return (
                  <FormItem>
                    <div className="flex items-center justify-between">
                      <FormLabel>Cashier Slug</FormLabel>
                      <Button
                        type="button"
                        variant="ghost"
                        size="sm"
                        className="h-6 px-2 text-xs"
                        onClick={handleRegenerateSlug}
                        disabled={!cashierName}
                      >
                        <RotateCw className="mr-1 h-3 w-3" />
                        Regenerate
                      </Button>
                    </div>
                    <FormControl>
                      <div className="focus-within:ring-ring flex items-center overflow-hidden rounded-md border shadow-sm focus-within:ring-1">
                        <Input
                          className="border-0 shadow-none focus-visible:ring-0"
                          placeholder="cashier-link-slug"
                          {...field}
                          value={field.value ?? ""}
                        />
                      </div>
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                );
              }}
            />
            <FormField
              control={form.control}
              name="cashierPassword"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Password</FormLabel>
                  <FormControl>
                    <Input
                      type="password"
                      placeholder="••••••••"
                      {...field}
                      value={field.value ?? ""}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />
          </div>
        </div>
      )}

      {!createCashier && (
        <div className="bg-muted/30 border-border/50 rounded-lg border-2 border-dashed p-8 text-center">
          <p className="text-muted-foreground">
            No problem! You can skip this step and set up your team later.
          </p>
        </div>
      )}
    </div>
  );
}
