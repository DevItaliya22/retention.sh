"use client";

import {
  DEFAULT_EMAIL_DOMAIN_SUFFIX,
  EMAIL_DOMAIN_SUFFIXES,
} from "@/lib/constants/email-domains";
import type { WelcomeFormValues } from "@/lib/schemas/onboarding";
import { generateSlug } from "@/lib/utils/slug";
import {
  Button,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
  Input,
  InputGroup,
  InputGroupAddon,
  InputGroupInput,
  PasswordInput,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
  useFormContext,
} from "@reelo/ui/components";
import { useDebouncedCallback } from "@reelo/ui/hooks";
import { RotateCw } from "lucide-react";
import { useEffect, useRef } from "react";

export function CashierStep() {
  const form = useFormContext<WelcomeFormValues>();
  const cashierName = form.watch("cashierName");
  const cashierSlug = form.watch("cashierLinkSlug");
  const businessSlug = form.watch("businessSlug");
  const slugTouchedRef = useRef(false);
  const lastAutoGeneratedSlugRef = useRef("");

  const debouncedSetSlug = useDebouncedCallback((name: string) => {
    if (!slugTouchedRef.current && name) {
      const slug = generateSlug(name);
      lastAutoGeneratedSlugRef.current = slug;
      form.setValue("cashierLinkSlug", slug, { shouldValidate: true });
    }
  }, 300);

  useEffect(() => {
    if (cashierSlug && cashierSlug !== lastAutoGeneratedSlugRef.current) {
      slugTouchedRef.current = true;
    }
  }, [cashierSlug]);

  // Auto-set createCashier based on whether any field is filled (form ref stable to avoid effect loop)
  const cashierEmailLocalPart = form.watch("cashierEmailLocalPart");
  const cashierPassword = form.watch("cashierPassword");
  const formRef = useRef(form);
  formRef.current = form;
  useEffect(() => {
    const hasAnyValue =
      !!cashierName?.trim() ||
      !!cashierEmailLocalPart?.trim() ||
      !!cashierPassword?.trim() ||
      !!cashierSlug?.trim();
    formRef.current.setValue("createCashier", hasAnyValue, {
      shouldValidate: false,
    });
  }, [cashierName, cashierEmailLocalPart, cashierPassword, cashierSlug]);

  const handleRegenerateSlug = () => {
    if (cashierName) {
      const slug = generateSlug(cashierName);
      form.setValue("cashierLinkSlug", slug, { shouldValidate: true });
      slugTouchedRef.current = false;
      lastAutoGeneratedSlugRef.current = slug;
    }
  };

  return (
    <div className="grid gap-6">
      <FormField
        control={form.control}
        name="cashierName"
        render={({ field }) => (
          <FormItem>
            <FormLabel>Cashier Name</FormLabel>
            <FormControl>
              <Input
                variant="underline"
                placeholder="John Doe"
                autoComplete="off"
                {...field}
                value={field.value ?? ""}
                onChange={(e) => {
                  field.onChange(e);
                  const value = e.target.value;
                  if (value && !slugTouchedRef.current) {
                    debouncedSetSlug(value);
                  }
                }}
              />
            </FormControl>
            <FormMessage variant="banner" />
          </FormItem>
        )}
      />

      <div className="space-y-2">
        <FormLabel>Cashier Email</FormLabel>
        <InputGroup variant="underline">
          <FormField
            control={form.control}
            name="cashierEmailLocalPart"
            render={({ field }) => (
              <FormItem className="flex-1">
                <FormControl>
                  <InputGroupInput
                    placeholder="john"
                    className="placeholder:text-muted-foreground/60 h-auto px-0 py-3 text-base"
                    {...field}
                    value={field.value ?? ""}
                  />
                </FormControl>
              </FormItem>
            )}
          />
          <InputGroupAddon className="px-0 py-3">
            @{businessSlug || "slug"}
          </InputGroupAddon>
          <FormField
            control={form.control}
            name="cashierEmailSuffix"
            render={({ field }) => (
              <FormItem className="shrink-0">
                <Select
                  value={field.value || DEFAULT_EMAIL_DOMAIN_SUFFIX}
                  onValueChange={field.onChange}
                >
                  <FormControl>
                    <SelectTrigger className="h-auto w-auto border-0 bg-transparent py-3 text-sm shadow-none focus:ring-0 dark:bg-transparent">
                      <SelectValue />
                    </SelectTrigger>
                  </FormControl>
                  <SelectContent>
                    {EMAIL_DOMAIN_SUFFIXES.map((suffix) => (
                      <SelectItem key={suffix.value} value={suffix.value}>
                        {suffix.label}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
              </FormItem>
            )}
          />
        </InputGroup>
        <FormField
          control={form.control}
          name="cashierEmailLocalPart"
          render={() => <FormMessage variant="banner" />}
        />
      </div>

      <FormField
        control={form.control}
        name="cashierPassword"
        render={({ field }) => (
          <FormItem>
            <FormLabel>Cashier Password</FormLabel>
            <FormControl>
              <PasswordInput
                variant="underline"
                placeholder="••••••••"
                {...field}
                value={field.value ?? ""}
              />
            </FormControl>
            <FormMessage variant="banner" />
          </FormItem>
        )}
      />

      <FormField
        control={form.control}
        name="cashierLinkSlug"
        render={({ field }) => (
          <FormItem>
            <div className="flex items-center justify-between">
              <FormLabel>Cashier Link Slug</FormLabel>
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className="h-6 px-2 text-xs"
                onClick={handleRegenerateSlug}
                disabled={!cashierName}
              >
                <RotateCw className="mr-1 h-3 w-3" />
                Regenerate
              </Button>
            </div>
            <FormControl>
              <Input
                variant="underline"
                placeholder="cashier-link-slug"
                {...field}
                value={field.value ?? ""}
              />
            </FormControl>
            <FormMessage variant="banner" />
          </FormItem>
        )}
      />
    </div>
  );
}
